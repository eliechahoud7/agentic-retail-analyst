"""Presentation layer for the Streamlit UI, free of Streamlit so it can be unit-tested.

It turns the workflow's final state into what a business user sees: either a clean answer
(heading, factual summary and results table, all generated by code from the verified data in
retail_analyst/summary.py) or a short message that no reliable answer could be produced.
The internal checks decide which of the two is shown:

- "scope" issues (causes, forecasts, relative or missing periods, no matching metric) -> refusal with its reason;
- "data" issues (no data, wrong grouping, truncated data, period not covered, step limit) -> no answer;
- "info" issues are diagnostics only (logged, not shown).
"""
from __future__ import annotations

import json
import re
import urllib.request
from typing import Callable

from sqlalchemy import text

from retail_analyst.config import get_engine, get_settings
from retail_analyst.state import RECURSION_LIMIT, AgentState, initial_state
from retail_analyst.summary import (answer_data, answer_markdown, column_label, format_value,  # noqa: F401
                                    heading_for, humanize_label, results_table, summary_text, table_kinds)

NO_RELIABLE_ANSWER = (
    "I couldn't produce a reliable answer to this question from the available data.\n\n"
    "Please try rephrasing it, for example by naming the measure (such as revenue, payments, "
    "delivery time or review scores) and how to group it (such as by category, state or month).")
SERVICE_UNAVAILABLE = "The analysis service is temporarily unavailable. Please try again in a moment."


def issues_of(state: AgentState, kind: str) -> list[str]:
    return [i["message"] for i in state.get("issues", []) if i.get("kind") == kind]


def result_rows(state: AgentState) -> list[dict]:
    """Rows of the answer (the verified catalog dataset)."""
    return answer_data(state)[0]


def user_answer(state: AgentState) -> tuple[bool, str]:
    """(reliable, markdown). Unreliable results are never shown as answers."""
    if scope := issues_of(state, "scope"):
        return False, f"I can't answer this question reliably. {scope[0]}"
    if not state.get("datasets") or not result_rows(state) or issues_of(state, "data"):
        return False, NO_RELIABLE_ANSWER
    return True, answer_markdown(state)


